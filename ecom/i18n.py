def get(lang, key, **fmt):
    try:
        text = I18N[lang][key]
    except KeyError:
        text = key
    if fmt:
        try:
            return text.format(**fmt)
        except (IndexError, KeyError):
            return text
    return text


def lang_label(lang):
    """语言的本名（不随当前语言翻译）。"""
    return "中文" if lang == "zh" else "English"
